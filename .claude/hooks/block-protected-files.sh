#!/usr/bin/env bash
# PreToolUse guard for Read/Edit/MultiEdit/Write (see docs/16-claude-code-setup.md §7.2).
# Read:  blocks every .env / .env.<name> file except .env.example (secrets are not readable by agents).
# Edits: also blocks lockfiles and generated API files, naming the command to use instead.
# Paths are matched by name or suffix, so files in git worktrees and behind ".." are covered too.
# Input: the hook JSON on stdin. Exit 2 = block (stderr is shown to Claude). Exit 0 = allow.
set -u
set -f # no globbing while splitting paths

input="$(cat)"

# Extract tool_name and tool_input.file_path: jq, else python3, else a plain sed match.
if command -v jq >/dev/null 2>&1; then
  tool="$(printf '%s' "$input" | jq -r '.tool_name // empty' 2>/dev/null)"
  file="$(printf '%s' "$input" | jq -r '.tool_input.file_path // .tool_input.notebook_path // empty' 2>/dev/null)"
elif command -v python3 >/dev/null 2>&1; then
  parsed="$(printf '%s' "$input" | python3 -I -c '
import json, sys
try:
    data = json.load(sys.stdin)
except Exception:
    sys.exit(0)
ti = data.get("tool_input") or {}
print(data.get("tool_name") or "")
print(ti.get("file_path") or ti.get("notebook_path") or "")
' 2>/dev/null)"
  tool="${parsed%%$'\n'*}"
  case "$parsed" in *$'\n'*) file="${parsed#*$'\n'}" ;; *) file="" ;; esac
else
  tool="$(printf '%s' "$input" | sed -n 's/.*"tool_name"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' | head -n 1)"
  file="$(printf '%s' "$input" | sed -n 's/.*"file_path"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' | head -n 1)"
fi

[ -n "${file:-}" ] || exit 0

# normalise <path>: drop "." segments and resolve ".." lexically (the file may not exist yet). Bash 3.2 safe.
normalise() {
  local IFS=/ part lead="" n
  local -a parts
  parts=()
  case "$1" in /*) lead=/ ;; esac
  for part in $1; do
    case "$part" in
      "" | .) ;;
      ..)
        n=${#parts[@]}
        if [ "$n" -gt 0 ] && [ "${parts[$((n - 1))]}" != .. ]; then
          unset "parts[$((n - 1))]"
        elif [ -z "$lead" ]; then
          parts[n]=..
        fi
        ;;
      *) parts[${#parts[@]}]="$part" ;;
    esac
  done
  if [ ${#parts[@]} -gt 0 ]; then printf '%s%s\n' "$lead" "${parts[*]}"; else printf '%s\n' "${lead:-.}"; fi
}

file="$(normalise "$file")"
root="${CLAUDE_PROJECT_DIR:-$(cd "$(dirname "$0")/../.." && pwd)}"
case "$file" in
  "$root"/*) rel="${file#"$root"/}" ;;
  *) rel="$file" ;;
esac
base="${file##*/}"

block() {
  printf 'Blocked: %s must not be edited by hand. %s\n' "$rel" "$1" >&2
  exit 2
}

case "$base" in
  .env.example)
    ;; # placeholders only, no secrets: allowed
  .env | .env.*)
    if [ "${tool:-}" = Read ]; then
      printf 'Blocked: %s holds secrets; secrets files are not readable by agents. Variable names are in .env.example; ask the user for any value you need.\n' "$rel" >&2
      exit 2
    fi
    block "It holds secrets. Put new variables with placeholder values in .env.example and ask the user to update their own env file." ;;
esac

[ "${tool:-}" != Read ] || exit 0 # lockfiles and generated files are fine to read

case "$base" in
  uv.lock)
    block "It is generated by uv. Change dependencies with 'uv add <pkg>' / 'uv remove <pkg>' in backend/ (or 'uv lock')." ;;
  pnpm-lock.yaml)
    block "It is generated by pnpm. Change dependencies with 'pnpm add <pkg>' / 'pnpm remove <pkg>' in frontend/." ;;
esac

case "$file" in
  frontend/src/lib/api/schema.d.ts | */frontend/src/lib/api/schema.d.ts | frontend/openapi.json | */frontend/openapi.json)
    block "It is generated from the FastAPI OpenAPI spec. Change the backend router or schema, then run 'make api-sync'." ;;
esac

exit 0
