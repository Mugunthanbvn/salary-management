#!/usr/bin/env bash
# PreToolUse guard for Edit/Write (see docs/16-claude-code-setup.md §7.2).
# Blocks hand edits to lockfiles, generated API files and .env files (except .env.example).
# Input: the hook JSON on stdin. Exit 2 = block (stderr is shown to Claude). Exit 0 = allow.
set -u

input="$(cat)"

# Extract tool_input.file_path: jq, else python3, else a plain sed match.
if command -v jq >/dev/null 2>&1; then
  file="$(printf '%s' "$input" | jq -r '.tool_input.file_path // .tool_input.notebook_path // empty' 2>/dev/null)"
elif command -v python3 >/dev/null 2>&1; then
  file="$(printf '%s' "$input" | python3 -I -c '
import json, sys
try:
    ti = json.load(sys.stdin).get("tool_input") or {}
except Exception:
    sys.exit(0)
print(ti.get("file_path") or ti.get("notebook_path") or "")
' 2>/dev/null)"
else
  file="$(printf '%s' "$input" | sed -n 's/.*"file_path"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' | head -n 1)"
fi

[ -n "${file:-}" ] || exit 0

root="${CLAUDE_PROJECT_DIR:-$(cd "$(dirname "$0")/../.." && pwd)}"
case "$file" in
  "$root"/*) rel="${file#"$root"/}" ;;
  *) rel="${file#./}" ;;
esac
base="$(basename "$file")"

block() {
  printf 'Blocked: %s must not be edited by hand. %s\n' "$rel" "$1" >&2
  exit 2
}

case "$base" in
  uv.lock)
    block "It is generated by uv. Change dependencies with 'uv add <pkg>' / 'uv remove <pkg>' in backend/ (or 'uv lock')." ;;
  pnpm-lock.yaml)
    block "It is generated by pnpm. Change dependencies with 'pnpm add <pkg>' / 'pnpm remove <pkg>' in frontend/." ;;
  .env.example)
    ;; # placeholders only, no secrets: allowed
  .env | .env.*)
    block "It holds secrets. Put new variables with placeholder values in .env.example and ask the user to update their own env file." ;;
esac

case "$rel" in
  frontend/src/lib/api/schema.d.ts | frontend/openapi.json)
    block "It is generated from the FastAPI OpenAPI spec. Change the backend router or schema, then run 'make api-sync'." ;;
esac

exit 0
